import os
from pathlib import Path
from typing import Dict, Optional
import docx
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import nsdecls, qn
from backend.app.config import settings
from backend.app.models.schemas import (
    ParameterKey, ParameterExtraction, ORDERED_PARAMETER_KEYS,
    PARAMETER_DISPLAY_NAMES, VerificationStatus
)

def set_cell_margins(cell, top=100, bottom=100, left=150, right=150):
    """Set inner padding for a table cell in dxa (1 pt = 20 dxa)."""
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = OxmlElement('w:tcMar')
    for m, val in [('top', top), ('bottom', bottom), ('left', left), ('right', right)]:
        node = OxmlElement(f'w:{m}')
        node.set(qn('w:w'), str(val))
        node.set(qn('w:type'), 'dxa')
        tcMar.append(node)
    tcPr.append(tcMar)

def set_cell_background(cell, hex_color: str):
    """Set background shading color of a table cell."""
    tcPr = cell._tc.get_or_add_tcPr()
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{hex_color}"/>')
    tcPr.append(shd)

def set_cell_borders(cell, top="CCCCCC", bottom="CCCCCC", left=None, right=None):
    """Set thin clean borders on a cell."""
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement('w:tcBorders')
    
    borders = {'top': top, 'bottom': bottom}
    if left:
        borders['left'] = left
    if right:
        borders['right'] = right
        
    for border_name, color in borders.items():
        if color:
            b = parse_xml(f'<w:{border_name} {nsdecls("w")} w:val="single" w:sz="4" w:space="0" w:color="{color}"/>')
            tcBorders.append(b)
        else:
            b = parse_xml(f'<w:{border_name} {nsdecls("w")} w:val="none"/>')
            tcBorders.append(b)
    tcPr.append(tcBorders)

class WordReportGenerator:
    """
    Generates a high-quality, professional Microsoft Word (.docx) tender analysis summary.
    Constrained to exactly the 12 parameters in a clean 2-column table.
    """

    @staticmethod
    def generate_report(document_id: str, original_filename: str,
                        parameters: Dict[str, ParameterExtraction],
                        output_path: Optional[Path] = None) -> Path:
        if not output_path:
            output_path = settings.REPORT_PATH / f"{document_id}_summary.docx"

        doc = docx.Document()

        # Set page margins: 0.6 inches for a compact, readable 1-page target layout
        for section in doc.sections:
            section.top_margin = Inches(0.55)
            section.bottom_margin = Inches(0.55)
            section.left_margin = Inches(0.65)
            section.right_margin = Inches(0.65)
            section.header_distance = Inches(0.2)
            section.footer_distance = Inches(0.2)

        # Document Header / Title
        title_para = doc.add_paragraph()
        title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        title_para.paragraph_format.space_before = Pt(0)
        title_para.paragraph_format.space_after = Pt(2)
        
        run_title = title_para.add_run("TENDER ANALYSIS & EXECUTIVE SUMMARY")
        run_title.font.name = "Calibri"
        run_title.font.size = Pt(14)
        run_title.font.bold = True
        run_title.font.color.rgb = RGBColor(26, 54, 93)  # Deep Navy

        # Subtitle / Document Reference
        sub_para = doc.add_paragraph()
        sub_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        sub_para.paragraph_format.space_before = Pt(0)
        sub_para.paragraph_format.space_after = Pt(8)
        
        run_sub = sub_para.add_run(f"Source File: {original_filename}  |  Generated by AI Tender Intelligence")
        run_sub.font.name = "Calibri"
        run_sub.font.size = Pt(8.5)
        run_sub.font.italic = True
        run_sub.font.color.rgb = RGBColor(100, 116, 139)  # Slate grey

        # Create the 12 Parameters Table: 1 Header row + 12 Data rows
        table = doc.add_table(rows=13, cols=2)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = False

        # Column widths: Col 1 (Parameter) = 1.9 inches, Col 2 (Summary) = 5.3 inches
        col_widths = [Inches(1.85), Inches(5.35)]
        for row in table.rows:
            for i, w in enumerate(col_widths):
                row.cells[i].width = w

        # Header Row
        hdr_cells = table.rows[0].cells
        hdr_cells[0].text = "Parameter"
        hdr_cells[1].text = "Extracted Tender Details & Obligations"
        
        for i, cell in enumerate(hdr_cells):
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            set_cell_background(cell, "1E3A8A")  # Professional Dark Blue
            set_cell_margins(cell, top=120, bottom=120, left=140, right=140)
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.space_before = Pt(0)
            p.paragraph_format.space_after = Pt(0)
            for r in p.runs:
                r.font.name = "Calibri"
                r.font.size = Pt(10)
                r.font.bold = True
                r.font.color.rgb = RGBColor(255, 255, 255)

        # 12 Parameter Rows
        for row_idx, key in enumerate(ORDERED_PARAMETER_KEYS, start=1):
            cell_param = table.rows[row_idx].cells[0]
            cell_value = table.rows[row_idx].cells[1]
            
            param_obj = parameters.get(key.value)
            display_name = PARAMETER_DISPLAY_NAMES[key]
            
            # Left Column: Parameter Name
            cell_param.vertical_alignment = WD_ALIGN_VERTICAL.TOP
            # Zebra subtle shading on alternating rows
            bg_color = "F8FAFC" if row_idx % 2 == 1 else "FFFFFF"
            set_cell_background(cell_param, bg_color)
            set_cell_background(cell_value, bg_color)
            set_cell_borders(cell_param, top="E2E8F0", bottom="E2E8F0")
            set_cell_borders(cell_value, top="E2E8F0", bottom="E2E8F0")
            set_cell_margins(cell_param, top=80, bottom=80, left=120, right=100)
            set_cell_margins(cell_value, top=80, bottom=80, left=120, right=100)

            p_param = cell_param.paragraphs[0]
            p_param.paragraph_format.space_before = Pt(0)
            p_param.paragraph_format.space_after = Pt(0)
            run_pname = p_param.add_run(display_name)
            run_pname.font.name = "Calibri"
            run_pname.font.size = Pt(9.5)
            run_pname.font.bold = True
            run_pname.font.color.rgb = RGBColor(30, 41, 59)

            # Right Column: Extracted Value / Reviewed Value / Missing Em Dash / Conflict
            p_val = cell_value.paragraphs[0]
            p_val.paragraph_format.space_before = Pt(0)
            p_val.paragraph_format.space_after = Pt(0)

            if not param_obj or param_obj.extracted_value == "—" or param_obj.status == VerificationStatus.MISSING:
                r_val = p_val.add_run("—")
                r_val.font.name = "Calibri"
                r_val.font.size = Pt(9.5)
                r_val.font.color.rgb = RGBColor(148, 163, 184)
            else:
                val_text = param_obj.final_value if param_obj.final_value else param_obj.extracted_value
                
                # Check if conflict exists
                if param_obj.conflict_status or param_obj.status == VerificationStatus.CONFLICT:
                    # Mark clearly with concise warning tag
                    r_warn = p_val.add_run("[CONFLICT DETECTED - REQUIRES REVIEW]\n")
                    r_warn.font.name = "Calibri"
                    r_warn.font.size = Pt(8.5)
                    r_warn.font.bold = True
                    r_warn.font.color.rgb = RGBColor(194, 65, 12)  # Amber-Red
                    
                r_val = p_val.add_run(val_text)
                r_val.font.name = "Calibri"
                r_val.font.size = Pt(9.0)
                r_val.font.color.rgb = RGBColor(15, 23, 42)
                
                # Add tiny page reference annotation at end
                if param_obj.source_pages:
                    pages_str = ", ".join(map(str, param_obj.source_pages))
                    r_pg = p_val.add_run(f" (Page: {pages_str})")
                    r_pg.font.name = "Calibri"
                    r_pg.font.size = Pt(8.0)
                    r_pg.font.italic = True
                    r_pg.font.color.rgb = RGBColor(100, 116, 139)

        # Footer note
        doc.add_paragraph().paragraph_format.space_after = Pt(2)
        note_para = doc.add_paragraph()
        note_para.paragraph_format.space_before = Pt(2)
        note_para.paragraph_format.space_after = Pt(0)
        r_note = note_para.add_run(
            "Note: This summary is strictly confined to the 12 predefined parameters extracted from source evidence. "
            "Conflicting and unverified parameters require human review before binding procurement actions."
        )
        r_note.font.name = "Calibri"
        r_note.font.size = Pt(7.5)
        r_note.font.italic = True
        r_note.font.color.rgb = RGBColor(148, 163, 184)

        doc.save(str(output_path))
        return output_path

docx_generator = WordReportGenerator()
